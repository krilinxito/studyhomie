#!/usr/bin/env node
// Writes the Scoop manifest, the Homebrew formula and the Chocolatey package for a release, with
// the URLs and SHA-256 of its archives taken from the release's checksums.txt.
//
//   node packaging/render.mjs <tag> <checksums.txt> <out-dir>
//
// out-dir/scoop/studyhomie.json, out-dir/homebrew/studyhomie.rb, out-dir/choco/… (nuspec + tools)
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [tag, sumsPath, out] = process.argv.slice(2);
if (!tag || !sumsPath || !out) {
  console.error('usage: node packaging/render.mjs <tag> <checksums.txt> <out-dir>');
  process.exit(2);
}
const v = tag.startsWith('v') ? tag : `v${tag}`;
const version = v.slice(1);
const repo = 'krilinxito/studyhomie';
const site = 'https://studyhomie.maxi42.space';
const base = `https://github.com/${repo}/releases/download/${v}`;
const summary = 'AI study assistant that runs on your computer: guides with interactive visuals, the iceberg of prerequisites, roadmaps and practice until you can explain it.';

const sums = new Map();
for (const line of readFileSync(sumsPath, 'utf8').split('\n')) {
  const [hash, file] = line.trim().split(/\s+/);
  if (hash && file) sums.set(file.replace(/^\*/, ''), hash.toLowerCase());
}
function asset(os, arch) {
  const name = `studyhomie_${v}_${os}_${arch}`;
  const file = `${name}${os === 'windows' ? '.zip' : '.tar.gz'}`;
  const sha = sums.get(file);
  if (!sha) throw new Error(`checksums.txt has no entry for ${file}`);
  return { name, url: `${base}/${file}`, sha };
}
const write = (path, text) => {
  mkdirSync(join(path, '..'), { recursive: true });
  writeFileSync(path, text.replace(/\r\n/g, '\n'));
  console.log('wrote', path);
};

/* ---------- Scoop ---------- */
const win = asset('windows', 'amd64');
write(join(out, 'scoop', 'studyhomie.json'), JSON.stringify({
  version,
  description: summary,
  homepage: site,
  license: 'MIT',
  architecture: { '64bit': { url: win.url, hash: win.sha, extract_dir: win.name } },
  bin: 'studyhomie.exe',
  checkver: { github: `https://github.com/${repo}` },
  autoupdate: {
    architecture: {
      '64bit': {
        url: `https://github.com/${repo}/releases/download/v$version/studyhomie_v$version_windows_amd64.zip`,
        extract_dir: 'studyhomie_v$version_windows_amd64',
      },
    },
    hash: { url: '$baseurl/checksums.txt' },
  },
}, null, 2) + '\n');

/* ---------- Homebrew ---------- */
const mac = { arm: asset('darwin', 'arm64'), intel: asset('darwin', 'amd64') };
const lin = { arm: asset('linux', 'arm64'), intel: asset('linux', 'amd64') };
const block = (a) => `      url "${a.url}"\n      sha256 "${a.sha}"`;
write(join(out, 'homebrew', 'studyhomie.rb'), `# Generated by packaging/render.mjs in ${repo} for each release.
class Studyhomie < Formula
  desc "AI study assistant: guides, the iceberg of prerequisites, roadmaps and practice"
  homepage "${site}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block(mac.arm)}
    end
    on_intel do
${block(mac.intel)}
    end
  end

  on_linux do
    on_arm do
${block(lin.arm)}
    end
    on_intel do
${block(lin.intel)}
    end
  end

  def install
    bin.install "studyhomie"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/studyhomie version")
  end
end
`);

/* ---------- Chocolatey ---------- */
const xml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
write(join(out, 'choco', 'studyhomie.nuspec'), `<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://schemas.microsoft.com/packaging/2015/06/nuspec.xsd">
  <metadata>
    <id>studyhomie</id>
    <version>${version}</version>
    <title>StudyHomie</title>
    <authors>krilinxito</authors>
    <owners>krilinxito</owners>
    <projectUrl>${site}</projectUrl>
    <projectSourceUrl>https://github.com/${repo}</projectSourceUrl>
    <packageSourceUrl>https://github.com/${repo}/tree/main/packaging</packageSourceUrl>
    <docsUrl>https://github.com/${repo}#readme</docsUrl>
    <bugTrackerUrl>https://github.com/${repo}/issues</bugTrackerUrl>
    <licenseUrl>https://github.com/${repo}/blob/main/LICENSE</licenseUrl>
    <requireLicenseAcceptance>false</requireLicenseAcceptance>
    <iconUrl>https://cdn.jsdelivr.net/gh/${repo}@main/internal/web/static/favicon.png</iconUrl>
    <releaseNotes>https://github.com/${repo}/releases/tag/${v}</releaseNotes>
    <tags>study learning ai obsidian markdown flashcards feynman cli</tags>
    <summary>${xml(summary)}</summary>
    <description>${xml(`StudyHomie is an AI study assistant that runs on your computer. Ask for what you want to understand and it writes a guide with interactive visuals, maps the iceberg of what the topic takes for granted, builds roadmaps for whole subjects and makes you practice (questions that ask you to reason, and the Feynman method) until you can explain it. Your notes stay on your disk as Markdown, compatible with Obsidian. It works with the AI you already have: Claude Code, Codex, Antigravity, an API key or a local model.

After installing, in a folder for your studies: \`studyhomie init\`, then \`studyhomie\`.`)}</description>
  </metadata>
  <files>
    <file src="tools\\**" target="tools" />
  </files>
</package>
`);
write(join(out, 'choco', 'tools', 'chocolateyinstall.ps1'), `$ErrorActionPreference = 'Stop'
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Definition

Install-ChocolateyZipPackage -PackageName $env:ChocolateyPackageName \`
  -Url64bit '${win.url}' \`
  -Checksum64 '${win.sha}' -ChecksumType64 'sha256' \`
  -UnzipLocation $toolsDir
`);
